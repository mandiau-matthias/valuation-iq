class TriageFlag(BaseModel):
    """A single triage flag returned by ValuationIQ.

    CTO SPEC: ValuationIQ returns *flags*, not questions.
    It identifies *that* something is wrong, not *how* to ask the user.
    Titan converts these flags to questions via Claude.
    """

    field: str = Field(..., description="Field with the issue (e.g., 'rent_expense')")
    issue: str = Field(..., description="Issue code (e.g., 'below_market_benchmark')")
    severity: str = Field(default="warning", description="Severity: 'info', 'warning', 'error'")
    value: Optional[object] = Field(None, description="Current value of the field")
    benchmark: Optional[object] = Field(None, description="Benchmark value for comparison")
    deviation_percent: Optional[Decimal] = Field(
        None, description="Percentage deviation from benchmark"
    )


class Artifacts(BaseModel):
    """Report artifacts generated by ValuationIQ.

    CTO SPEC: ValuationIQ generates PDF and HTML as artifacts
    that Titan stores and serves to the frontend.
    """

    pdf_base64: Optional[str] = Field(None, description="Base64-encoded PDF report")
    html_preview: Optional[str] = Field(None, description="HTML preview string for frontend")
    report_data: Optional[JsonObject] = Field(
        None, description="Structured JSON for React template"
    )


class MethodResult(BaseModel):
    """A single valuation method's result within the Omni-Calc output.

    The five trailing `method_key`/`confidence`/`value_low`/`value_high`/
    `engine_version` fields are the report-layer contract added 2026-05-15
    so a Jinja macro (`shared/macros/method_section.html`) and the
    multi-method synthesizer can consume any method's output without
    knowing its concrete engine. All five are Optional and default to
    None so existing engine call sites keep working unchanged.
    """

    value: Optional[Decimal] = Field(None, description="Equity value for this method")
    enterprise_value: Optional[Decimal] = Field(
        None,
        description="Explicit method enterprise value before any EV-to-equity bridge.",
    )
    enterprise_value_low: Optional[Decimal] = None
    enterprise_value_high: Optional[Decimal] = None
    equity_value: Optional[Decimal] = Field(
        None,
        description="Explicit method equity value; value remains the compatibility alias.",
    )
    equity_value_low: Optional[Decimal] = None
    equity_value_high: Optional[Decimal] = None
    value_basis: Literal["equity_value", "enterprise_value"] = Field(
        "equity_value",
        description=(
            "Basis of value/value_low/value_high. Stateless method results are "
            "equity values unless a calculator explicitly declares enterprise value."
        ),
    )
    label: str = Field(..., description="Human-readable label (e.g. 'UpSwitch Adaptive')")
    multiple_used: Optional[Decimal] = Field(
        None, description="Multiple applied (EV/EBITDA, SDE, etc.)"
    )
    wacc: Optional[Decimal] = Field(None, description="WACC used (DCF only)")
    available: bool = Field(True, description="False when method cannot compute for this input")
    unavailable_reason: Optional[str] = Field(None, description="Why the method is unavailable")
    details: Optional[JsonObject] = Field(None, description="Method-specific detail payload")

    method_key: Optional[MethodKey] = Field(
        None,
        description=(
            "Stable registry key. Typed as a Pydantic Literal sourced from "
            "`src.domain.method_keys.MethodKey` so an unknown key fails at "
            "validation time instead of silently disabling the citation "
            "block. Must match the keys in "
            "`templates/main_report/components/_method_citations.html` and "
            "`WeightedMethodContribution.method_key`."
        ),
    )
    confidence: Optional[Literal["high", "medium", "low"]] = Field(
        None, description="Per-method confidence band (separate from top-level confidence_level)"
    )
    value_low: Optional[Decimal] = Field(None, description="Lower bound of equity-value range")
    value_high: Optional[Decimal] = Field(None, description="Upper bound of equity-value range")
    engine_version: Optional[str] = Field(
        None, description="Calculation model version that produced this result (for audit trail)"
    )


class ValuationTimelinePoint(BaseModel):
    """One fiscal year of the per-year valuation curve.

    Each point is a FULL adaptive valuation of that single year's financials,
    computed on the CURRENT market lens (today's resolved benchmark multiples /
    calibration / macro) — a "restated" value, not a historical mark. The
    latest-actual-year point reconciles to the headline by construction. See
    `src/services/reports/stateless_valuation_timeline.py`.
    """

    fiscal_year: int = Field(..., description="Fiscal year this point values")
    equity_low: Decimal = Field(..., ge=0)
    equity_mid: Decimal = Field(..., ge=0)
    equity_high: Decimal = Field(..., ge=0)
    enterprise_value_low: Optional[Decimal] = Field(None, ge=0)
    enterprise_value_mid: Optional[Decimal] = Field(None, ge=0)
    enterprise_value_high: Optional[Decimal] = Field(None, ge=0)
    value_basis: Literal["equity_value", "enterprise_value"] = "equity_value"
    currency: Optional[str] = Field(
        default=None,
        pattern=r"^[A-Z]{3}$",
        description=(
            "ISO-4217 currency of this point's band. None means unresolved; the API "
            "must not silently relabel it as EUR."
        ),
    )
    methodology_used: Optional[str] = Field(
        None, description="Adaptive methodology selected for this year (e.g. HYBRID, MULTIPLES)"
    )
    confidence_level: Optional[str] = Field(None, description="LOW, MEDIUM, HIGH for this year")
    confidence_score: Optional[int] = Field(None, ge=0, le=100)
    audit_snapshot: Optional[JsonObject] = Field(
        default=None,
        description=(
            "Immutable public-valuation audit for this exact fiscal-year point. "
            "Present only when the request enabled the public audit contract."
        ),
    )
    is_forecast: bool = Field(
        default=False, description="True when this year is a user-supplied forecast/projection"
    )
    source_as_of: Optional[str] = Field(
        None,
        description="Newest source evidence date for this fiscal point; never a carried-forward lens date.",
    )
    qualifications: List[str] = Field(
        default_factory=list,
        description=(
            "Point-specific limitations. In particular, measurement-date bridge facts "
            "without an effective fiscal date are excluded from non-anchor restatements."
        ),
    )


