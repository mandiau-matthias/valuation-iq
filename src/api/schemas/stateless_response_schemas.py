    # Pydantic drops defaults from custom serializer schemas; the three field
    # declarations preserve their existing public null defaults explicitly.
    @field_serializer(
        "multiples_results", "value_driver_ledger", "earnings_basis_ledger", when_used="json"
    )
    @staticmethod
    def serialize_committed_json_facts(value: Optional[JsonObject]) -> Optional[JsonObject]:
        # Opaque JSON facts must retain the Decimal spelling sealed into the run.
        # Pydantic otherwise writes small zeros as exponent text (e.g. 0E-28).
        return valuation_wire_object(value)

    @model_validator(mode="after")
    def reconcile_immutable_run(self) -> "CalculateResponse":
        """Reject a response envelope that disagrees with its hashed run."""
        equity_values = (
            self.equity_value_low,
            self.equity_value_mid,
            self.equity_value_high,
        )
        if all(value is None for value in equity_values):
            enterprise_only = bool(
                self.valuation_run is not None
                and self.valuation_run.value_basis == "enterprise_value"
                and self.valuation_run.valuation_range.value_basis == "enterprise_value"
                and self.financial_metrics.get("equity_status") == "unavailable_incomplete_bridge"
                and all(
                    value is not None
                    for value in (
                        self.enterprise_value_low,
                        self.enterprise_value_mid,
                        self.enterprise_value_high,
                    )
                )
            )
            resolution = self.negative_ebitda_resolution
            equity_bridge = resolution.equity_bridge if resolution is not None else None
            conditional_shareholder_value = bool(
                resolution is not None
                and resolution.primary_method == "recovery_dcf"
                and isinstance(equity_bridge, dict)
                and equity_bridge.get("shareholder_equity_status") == "conditional"
                and all(
                    value is not None
                    for value in (
                        self.enterprise_value_low,
                        self.enterprise_value_mid,
                        self.enterprise_value_high,
                    )
                )
            )
            nonnumeric_assessment = bool(
                resolution is not None
                and resolution.status == "no_going_concern_range"
                and resolution.primary_method is None
            )
            if (
                not nonnumeric_assessment
                and not conditional_shareholder_value
                and not enterprise_only
            ):
                raise ValueError(
                    "null equity bands require a nonnumeric recovery assessment or a "
                    "conditional shareholder bridge with an enterprise-value band"
                )
            if self.status != "WARNINGS":
                raise ValueError("a null-band recovery assessment must have WARNINGS status")
            if self.recommended_asking_price is not None:
                raise ValueError("a null-band recovery assessment cannot carry an asking price")
            if self.valuation_run is not None and not enterprise_only:
                raise ValueError("a null-band assessment cannot create a numeric valuation_run")
            if self.valuation_timeline is not None or self.forward_value_cone is not None:
                raise ValueError("a null-band assessment cannot create a value curve")
        elif any(value is None for value in equity_values):
            raise ValueError("equity_value_low/mid/high must be supplied together or all be null")

        run = self.valuation_run
        if run is None:
            return self

        equity_low, equity_mid, equity_high = equity_values

        if run.valuation_id is not None and run.valuation_id != self.valuation_id:
            raise ValueError("valuation_id does not match valuation_run.valuation_id")
        if run.calculation_timestamp != self.calculation_timestamp:
            raise ValueError(
                "calculation_timestamp does not match valuation_run.calculation_timestamp"
            )
        if run.methodology_used != self.methodology_used:
            raise ValueError("methodology_used does not match valuation_run.methodology_used")

        if run.valuation_range.value_basis == "equity_value":
            if equity_low is None or equity_mid is None or equity_high is None:
                raise ValueError("equity run requires a complete equity band")
            _assert_run_range_matches(
                label="equity",
                run_range=run.valuation_range,
                low=equity_low,
                mid=equity_mid,
                high=equity_high,
            )
        enterprise_values = (
            self.enterprise_value_low,
            self.enterprise_value_mid,
            self.enterprise_value_high,
        )
        if all(value is None for value in enterprise_values):
            if run.enterprise_value_range is not None:
                raise ValueError(
                    "enterprise value is not applicable in the response but valuation_run carries a range"
                )
        elif any(value is None for value in enterprise_values):
            raise ValueError(
                "enterprise_value_low/mid/high must be supplied together or all be null"
            )
        else:
            if run.enterprise_value_range is None:
                raise ValueError(
                    "enterprise value is present in the response but not applicable in valuation_run"
                )
            enterprise_low, enterprise_mid, enterprise_high = enterprise_values
            assert enterprise_low is not None
            assert enterprise_mid is not None
            assert enterprise_high is not None
            _assert_run_range_matches(
                label="enterprise",
                run_range=run.enterprise_value_range,
                low=enterprise_low,
                mid=enterprise_mid,
                high=enterprise_high,
            )
            if run.valuation_range.value_basis == "enterprise_value":
                _assert_run_range_matches(
                    label="enterprise headline",
                    run_range=run.valuation_range,
                    low=enterprise_low,
                    mid=enterprise_mid,
                    high=enterprise_high,
                )
        if (
            self.methodology_used == "WEIGHTED_SYNTHESIS"
            and self.weighted_valuation is not None
            and self.weighted_valuation.blended_equity_value != equity_mid
        ):
            raise ValueError(
                "weighted_valuation.blended_equity_value does not match equity_value_mid"
            )
        _assert_run_payload_matches(
            label="valuation_results",
            outer=self.valuation_results or {},
            committed=run.method_results,
        )
        _assert_run_payload_matches(
            label="weighted_valuation",
            outer=self.weighted_valuation,
            committed=run.weighted_valuation,
        )
        _assert_run_payload_matches(
            label="methodology_weights",
            outer={"dcf": self.dcf_weight, "multiples": self.multiples_weight},
            committed=run.methodology_weights,
        )
        _assert_run_payload_matches(
            label="financial_metrics",
            outer=self.financial_metrics,
            committed=run.financial_metrics,
        )
        _assert_run_payload_matches(
            label="dcf_results",
            outer=self.dcf_results,
            committed=run.dcf_results,
        )
        _assert_run_payload_matches(
            label="multiples_results",
            outer=self.multiples_results,
            committed=run.multiples_results,
        )
        _assert_run_payload_matches(
            label="value_driver_ledger",
            outer=self.value_driver_ledger or {},
            committed=run.driver_ledger,
        )
        projection_layers = run.projection_layers
        _assert_run_payload_matches(
            label="valuation_timeline",
            outer=self.valuation_timeline,
            committed=projection_layers.get("current_lens_restatements"),
        )
        _assert_run_payload_matches(
            label="forward_value_cone",
            outer=self.forward_value_cone,
            committed=projection_layers.get("base_forecasts_and_scenarios"),
        )
        _assert_run_payload_matches(
            label="triage_flags",
            outer=self.triage_flags,
            committed=run.qualifications,
        )
        from src.services.reports.stateless_valuation_run import (
            valuation_response_snapshot,
        )

        # These release signals were added to valuation_run.v2 after the first
        # response envelope shipped. When an older consumer rehydrates the
        # response without duplicating them at top level, source them only from
        # the already hash-verified run; an explicitly supplied mismatch still
        # fails below.
        for field in (
            "publication_allowed",
            "publication_blocked",
            "report_readiness_state",
            "defensibility_review_state",
        ):
            if field not in self.model_fields_set and field in run.response_snapshot:
                setattr(self, field, run.response_snapshot[field])

        outer_response_snapshot = valuation_response_snapshot(self)
        committed_response_snapshot = valuation_response_snapshot(run.response_snapshot)
        if run.schema_version == "valuation_run.v1":
            committed_keys = set(run.response_snapshot)
            outer_response_snapshot = {
                key: value
                for key, value in outer_response_snapshot.items()
                if key in committed_keys
            }
            committed_response_snapshot = {
                key: value
                for key, value in committed_response_snapshot.items()
                if key in committed_keys
            }
        _assert_run_payload_matches(
            label="response_snapshot",
            outer=outer_response_snapshot,
            committed=committed_response_snapshot,
        )
        return self
