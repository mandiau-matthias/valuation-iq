"""
Manual Valuation Streaming Endpoint
Stream complete HTML report after valuation calculation completes.

Architecture:
- Full valuation calculation completes first (including html_report generation)
- Complete html_report is then streamed via SSE
- No progressive section-by-section generation (full report is generated upfront)

Note: The html_report is generated by html_report_service.py before streaming starts.
This endpoint streams the already-complete report, providing real-time delivery
but not progressive generation.
"""

import json
import logging
import time
import uuid
from decimal import Decimal
from typing import Any, AsyncGenerator, Dict, Optional

from fastapi import APIRouter, HTTPException
from fastapi.responses import StreamingResponse

from src.api.routes.valuation.valuation_orchestrator import get_valuation_orchestrator
from src.api.schemas import ValuationRequest, ValuationResponse
from src.services.progressive.html_optimizer import StreamingHTMLOptimizer

# Import moved inside functions to avoid circular import
# from src.api.streaming.sse import get_sse_headers, format_sse_event
# REMOVED: from src.services.templates.template_service import ValuationTemplateService (deprecated, use HTMLReportService)
from src.utils.decimal_helpers import from_decimal, to_decimal
from src.utils.logging import get_logger

logger = get_logger(__name__)


async def stream_manual_valuation(
    valuation_request: ValuationRequest,
    request_id: Optional[str] = None,
    correlation_id: Optional[str] = None,
) -> AsyncGenerator[str, None]:
    """
    Stream complete HTML report after valuation calculation completes.

    Architecture:
    - Full valuation calculation completes first (including html_report generation)
    - Complete html_report is then streamed via SSE
    - No progressive section-by-section generation (full report is generated upfront)

    Args:
        valuation_request: Manual valuation request from form
        request_id: Unique request identifier
        correlation_id: Correlation ID for tracing

    Yields:
        SSE-formatted JSON strings with:
        - Loading events during calculation (phase 1)
        - Complete HTML report event (phase 2)
        - Completion event with full response data
    """
    # Lazy import to avoid circular dependency
    from src.api.streaming.sse import format_sse_event

    if not request_id:
        request_id = str(uuid.uuid4())

    start_time = time.time()
    logger.info(f"[STREAM-MANUAL] Starting manual valuation stream | request_id={request_id}")

    try:
        # Initialize services
        orchestrator = get_valuation_orchestrator()
        # CRITICAL: Use orchestrator's HTMLReportService (has Smart Pagination!)
        # OLD: template_service = ValuationTemplateService()  # Deprecated, no pagination
        html_report_service = orchestrator.html_report_service
        html_optimizer = StreamingHTMLOptimizer()

        # Emit initial progress event
        try:
            yield format_sse_event(
                event_type="progress",
                data={
                    "progress": 0,
                    "status": "starting",
                    "message": "Initializing valuation calculation...",
                    "request_id": request_id,
                },
                event_id=f"progress_{request_id}_0",
            )
        except Exception as serialization_error:
            logger.error(
                "[STREAM-MANUAL] Failed to serialize initial progress event",
                extra={
                    "request_id": request_id,
                    "correlation_id": correlation_id,
                    "error": str(serialization_error),
                    "error_type": type(serialization_error).__name__,
                },
                exc_info=True,
            )
            # Try to send error event, but if that fails too, we'll let the outer exception handler catch it
            try:
                yield format_sse_event(
                    event_type="error",
                    data={
                        "error": "Serialization error during initialization",
                        "error_type": type(serialization_error).__name__,
                        "request_id": request_id,
                        "correlation_id": correlation_id,
                    },
                    event_id=f"error_{request_id}_init",
                )
            except (ValueError, TypeError, AttributeError, KeyError):
                pass
            raise

        # Phase 1: Basic calculation (0-30%)
        yield format_sse_event(
            event_type="section_loading",
            data={
                "section": "basic_valuation",
                "phase": 1,
                "progress": 10,
                "message": "Calculating basic valuation metrics...",
                "request_id": request_id,
            },
            event_id=f"section_{request_id}_basic_loading",
        )

        # Calculate basic valuation (this is the core calculation)
        context = {"correlation_id": correlation_id} if correlation_id else {}
        try:
            valuation_response = await orchestrator.process_comprehensive_valuation(
                valuation_request, context=context
            )
        except Exception as calc_error:
            logger.error(
                "[STREAM-MANUAL] Valuation calculation failed",
                extra={
                    "request_id": request_id,
                    "correlation_id": correlation_id,
                    "error": str(calc_error),
                    "error_type": type(calc_error).__name__,
                },
                exc_info=True,
            )
            # Send error event before re-raising
            try:
                yield format_sse_event(
                    event_type="error",
                    data={
                        "error": "Valuation calculation failed",
                        "error_type": type(calc_error).__name__,
                        "error_message": str(calc_error),
                        "request_id": request_id,
                        "correlation_id": correlation_id,
                    },
                    event_id=f"error_{request_id}_calculation",
                )
            except (ValueError, TypeError, AttributeError, KeyError):
                pass
            raise

        # CRITICAL: Comprehensive diagnostic logging after valuation calculation
        has_html_report_attr = hasattr(valuation_response, "html_report")
        html_report_value = valuation_response.html_report if has_html_report_attr else None
        has_html_report = bool(html_report_value)
        html_report_length = (
            len(html_report_value)
            if html_report_value and isinstance(html_report_value, str)
            else 0
        )
        html_report_type = type(html_report_value).__name__ if html_report_value else None
        html_report_is_string = isinstance(html_report_value, str) if html_report_value else False
        html_report_is_empty = html_report_length == 0 if html_report_value else True
        html_report_preview = (
            html_report_value[:200]
            if html_report_value
            and isinstance(html_report_value, str)
            and len(html_report_value) > 200
            else (html_report_value if html_report_value else None)
        )

        logger.info(
            "[STREAM-MANUAL] Valuation calculation complete, comprehensive html_report check",
            extra={
                "request_id": request_id,
                "correlation_id": correlation_id,
                "has_html_report_attr": has_html_report_attr,
                "html_report_value_is_none": html_report_value is None,
                "has_html_report": has_html_report,
                "html_report_length": html_report_length,
                "html_report_type": html_report_type,
                "html_report_is_string": html_report_is_string,
                "html_report_is_empty": html_report_is_empty,
                "html_report_preview": html_report_preview,
                "valuation_id": (
                    valuation_response.valuation_id
                    if hasattr(valuation_response, "valuation_id")
                    else None
                ),
                "response_type": type(valuation_response).__name__,
                "response_has_html_report_attr": hasattr(valuation_response, "html_report"),
                "response_dir_keys": (
                    [k for k in dir(valuation_response) if not k.startswith("_")][:20]
                    if hasattr(valuation_response, "__dict__")
                    else None
                ),
            },
        )

        # CRITICAL: Warn if html_report is missing or invalid
        if not has_html_report_attr:
            logger.error(
                "[STREAM-MANUAL] CRITICAL: valuation_response missing html_report attribute",
                extra={
                    "request_id": request_id,
                    "correlation_id": correlation_id,
                    "valuation_id": (
                        valuation_response.valuation_id
                        if hasattr(valuation_response, "valuation_id")
                        else None
                    ),
                    "response_type": type(valuation_response).__name__,
                    "response_attrs": [k for k in dir(valuation_response) if not k.startswith("_")][
                        :30
                    ],
                },
            )
        elif html_report_value is None:
            logger.warning(
                "[STREAM-MANUAL] WARNING: valuation_response.html_report is None",
                extra={
                    "request_id": request_id,
                    "correlation_id": correlation_id,
                    "valuation_id": (
                        valuation_response.valuation_id
                        if hasattr(valuation_response, "valuation_id")
                        else None
                    ),
                },
            )
        elif not html_report_is_string:
            logger.error(
                "[STREAM-MANUAL] CRITICAL: valuation_response.html_report is not a string",
                extra={
                    "request_id": request_id,
                    "correlation_id": correlation_id,
                    "html_report_type": html_report_type,
                    "html_report_value_preview": (
                        str(html_report_value)[:200] if html_report_value else None
                    ),
                },
            )
        elif html_report_is_empty:
            logger.warning(
                "[STREAM-MANUAL] WARNING: valuation_response.html_report is empty string",
                extra={
                    "request_id": request_id,
                    "correlation_id": correlation_id,
                    "valuation_id": (
                        valuation_response.valuation_id
                        if hasattr(valuation_response, "valuation_id")
                        else None
                    ),
                },
            )
        elif html_report_length < 1000:
            logger.warning(
                "[STREAM-MANUAL] WARNING: valuation_response.html_report is suspiciously short",
                extra={
                    "request_id": request_id,
                    "correlation_id": correlation_id,
                    "html_report_length": html_report_length,
                    "html_report_preview": html_report_preview,
                },
            )

        # Phase 2: Stream complete HTML report (30-100%)
        # Note: The full html_report is generated by html_report_service.py before streaming starts.
        # This phase streams the already-complete report, not progressive sections.
        if valuation_response.html_report and html_report_length > 0:
            # Stream complete HTML report (generated by html_report_service.py)
            logger.info(
                "[STREAM-MANUAL] Streaming complete HTML report",
                extra={
                    "request_id": request_id,
                    "correlation_id": correlation_id,
                    "html_report_length": html_report_length,
                    "valuation_id": valuation_response.valuation_id,
                    "html_report_preview": (
                        valuation_response.html_report[:200]
                        if html_report_length > 200
                        else valuation_response.html_report
                    ),
                },
            )
            try:
                # Validate that html_report is JSON-serializable
                json.dumps({"html": valuation_response.html_report})
                yield format_sse_event(
                    event_type="report_section",
                    data={
                        "section": "complete_report",
                        "phase": 2,
                        "html": valuation_response.html_report,
                        "progress": 90,
                        "request_id": request_id,
                        "valuation_id": valuation_response.valuation_id,
                    },
                    event_id=f"section_{request_id}_complete",
                )
            except (TypeError, ValueError) as serialization_error:
                logger.error(
                    "[STREAM-MANUAL] Failed to serialize HTML report in SSE event",
                    extra={
                        "request_id": request_id,
                        "correlation_id": correlation_id,
                        "error": str(serialization_error),
                        "error_type": type(serialization_error).__name__,
                        "html_report_length": html_report_length,
                        "html_report_type": type(valuation_response.html_report).__name__,
                    },
                    exc_info=True,
                )
                # Send error event with truncated/safe HTML
                try:
                    safe_html = (
                        str(valuation_response.html_report)[:10000]
                        if valuation_response.html_report
                        else ""
                    )
                    yield format_sse_event(
                        event_type="error",
                        data={
                            "error": "Failed to serialize HTML report",
                            "error_type": type(serialization_error).__name__,
                            "request_id": request_id,
                            "correlation_id": correlation_id,
                            "message": "HTML report serialization failed",
                        },
                        event_id=f"error_{request_id}_serialization",
                    )
                except (ValueError, TypeError, AttributeError, KeyError):
                    pass
                raise
            logger.info(
                "[STREAM-MANUAL] Complete report section event sent",
                extra={
                    "request_id": request_id,
                    "correlation_id": correlation_id,
                    "valuation_id": valuation_response.valuation_id,
                },
            )
        else:
            # BANK-GRADE: Fail fast with proper error handling instead of generating inferior fallback HTML
            # The main report generation is the single source of truth - if it fails, we should know about it
            error_message = (
                f"HTML report generation failed or returned empty result. "
                f"html_report_length={html_report_length}, "
                f"valuation_id={valuation_response.valuation_id}"
            )
            logger.error(
                "[STREAM-MANUAL] HTML report missing - failing fast instead of generating fallback",
                extra={
                    "request_id": request_id,
                    "correlation_id": correlation_id,
                    "valuation_id": valuation_response.valuation_id,
                    "html_report_length": html_report_length,
                    "has_html_report_attr": hasattr(valuation_response, "html_report"),
                    "html_report_type": (
                        type(valuation_response.html_report).__name__
                        if hasattr(valuation_response, "html_report")
                        else "N/A"
                    ),
                },
                exc_info=True,
            )
            yield format_sse_event(
                event_type="error",
                data={
                    "error": "HTML report generation failed",
                    "error_type": "ReportGenerationError",
                    "message": error_message,
                    "request_id": request_id,
                    "correlation_id": correlation_id,
                },
                event_id=f"error_{request_id}_missing_report",
            )
            # Don't raise exception here - let the completion event be sent so frontend can handle gracefully

        # Emit completion event - ALWAYS include html_report even if it was sent earlier
        total_time = time.time() - start_time
        final_html_report = (
            valuation_response.html_report if valuation_response.html_report else None
        )
        final_html_report_length = len(final_html_report) if final_html_report else 0

        logger.info(
            "[STREAM-MANUAL] Emitting report_complete event",
            extra={
                "request_id": request_id,
                "correlation_id": correlation_id,
                "valuation_id": valuation_response.valuation_id,
                "has_html_report": bool(final_html_report),
                "html_report_length": final_html_report_length,
                "duration_seconds": round(total_time, 2),
            },
        )

        try:
            # Validate completion data is JSON-serializable before sending
            completion_data = {
                "progress": 100,
                "status": "completed",
                "valuation_id": (
                    str(valuation_response.valuation_id)
                    if hasattr(valuation_response, "valuation_id")
                    else None
                ),
                "request_id": request_id,
                "duration_seconds": round(total_time, 2),
                "html_report": final_html_report,  # CRITICAL: Always include html_report in completion event
            }
            json.dumps(completion_data)  # Test serialization

            yield format_sse_event(
                event_type="report_complete",
                data=completion_data,
                event_id=f"complete_{request_id}",
            )
        except (TypeError, ValueError) as serialization_error:
            logger.error(
                "[STREAM-MANUAL] Failed to serialize completion event",
                extra={
                    "request_id": request_id,
                    "correlation_id": correlation_id,
                    "error": str(serialization_error),
                    "error_type": type(serialization_error).__name__,
                    "valuation_id": (
                        valuation_response.valuation_id
                        if hasattr(valuation_response, "valuation_id")
                        else None
                    ),
                },
                exc_info=True,
            )
            # Send completion event without html_report if it's causing issues
            try:
                yield format_sse_event(
                    event_type="report_complete",
                    data={
                        "progress": 100,
                        "status": "completed",
                        "valuation_id": (
                            str(valuation_response.valuation_id)
                            if hasattr(valuation_response, "valuation_id")
                            else None
                        ),
                        "request_id": request_id,
                        "duration_seconds": round(total_time, 2),
                        "html_report": None,
                        "warning": "HTML report excluded due to serialization error",
                    },
                    event_id=f"complete_{request_id}",
                )
            except Exception as fallback_error:
                logger.error(
                    "[STREAM-MANUAL] Even fallback completion event failed",
                    extra={
                        "request_id": request_id,
                        "correlation_id": correlation_id,
                        "fallback_error": str(fallback_error),
                    },
                    exc_info=True,
                )
                raise serialization_error

        logger.info(
            "[STREAM-MANUAL] Manual valuation stream completed",
            extra={
                "request_id": request_id,
                "correlation_id": correlation_id,
                "duration_seconds": round(total_time, 2),
                "final_html_report_length": final_html_report_length,
                "valuation_id": valuation_response.valuation_id,
            },
        )

    except Exception as e:
        logger.error(
            "[STREAM-MANUAL] Manual valuation stream failed",
            extra={
                "request_id": request_id,
                "correlation_id": correlation_id,
                "error": str(e),
                "error_type": type(e).__name__,
            },
            exc_info=True,
        )
        # Try to send error event, but handle serialization errors gracefully
        try:
            error_data = {
                "error": str(e)[:500],  # Truncate long error messages
                "error_type": type(e).__name__,
                "request_id": request_id,
                "correlation_id": correlation_id,
                "message": "Failed to generate valuation report",
            }
            # Validate error data is serializable
            json.dumps(error_data)
            yield format_sse_event(
                event_type="error", data=error_data, event_id=f"error_{request_id}"
            )
        except Exception as error_serialization_error:
            # If we can't even send an error event, log it and let the exception propagate
            logger.error(
                "[STREAM-MANUAL] CRITICAL: Failed to serialize error event",
                extra={
                    "request_id": request_id,
                    "correlation_id": correlation_id,
                    "original_error": str(e),
                    "original_error_type": type(e).__name__,
                    "serialization_error": str(error_serialization_error),
                },
                exc_info=True,
            )
            # Re-raise the original error
            raise e


# BANK-GRADE REFACTORING: Removed fallback HTML generation functions
#
# Rationale (Bank-Grade Excellence Audit):
# 1. Single Responsibility: Streaming endpoint should only stream, not generate HTML
# 2. No Duplication: Main report generation is the single source of truth
# 3. Fail Fast: Better to fail with proper error than silently generate inferior fallback
# 4. Transparency: If HTML generation fails, we should know about it, not hide it
# 5. Error Handling: Proper error handling > silent fallbacks
#
# If html_report is missing, the streaming endpoint now:
# - Logs a detailed error with full context
# - Emits an error SSE event for frontend handling
# - Allows completion event to be sent so frontend can handle gracefully
# - Does NOT generate inferior fallback HTML that duplicates main report functionality
#
# The main report generation in html_report_service.py is responsible for HTML generation.
# If it fails, that's a system error that should be fixed, not masked with fallbacks.


def create_manual_streaming_response(
    valuation_request: ValuationRequest,
    request_id: Optional[str] = None,
    correlation_id: Optional[str] = None,
    origin: Optional[str] = None,
) -> StreamingResponse:
    """
    Create FastAPI streaming response for manual valuation

    Args:
        valuation_request: Manual valuation request
        request_id: Unique request identifier
        correlation_id: Correlation ID for tracing
        origin: Request origin for CORS headers

    Returns:
        FastAPI StreamingResponse
    """
    # Lazy import to avoid circular dependency
    from src.api.streaming.sse import get_sse_headers

    async def generate() -> AsyncGenerator[str, None]:
        async for chunk in stream_manual_valuation(valuation_request, request_id, correlation_id):
            yield chunk

    return StreamingResponse(
        generate(), media_type="text/event-stream", headers=get_sse_headers(origin=origin)
    )
